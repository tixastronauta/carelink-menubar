import Foundation

@main
struct ModelChecks {
    static func main() throws {
        L10n.choice = .portuguese  // assertions below use the Portuguese source strings
        let now = Date(timeIntervalSince1970: 1_800_000_000)
        let timestamp = ISO8601DateFormatter().string(from: now)
        let json = """
        {"glucose":123,"unit":"mg/dL","timestamp":"\(timestamp)","trend":"UP_DOUBLE","active_insulin_units":0,"history":[{"timestamp":"\(timestamp)","glucose":123}],"synthetic":false}
        """
        let snapshot = try JSONDecoder().decode(Snapshot.self, from: Data(json.utf8))
        precondition(snapshot.glucoseText == "123")
        precondition(snapshot.trendSymbol == "↑↑")
        precondition(snapshot.activeInsulin == 0)
        precondition(snapshot.points.count == 1)
        precondition(!snapshot.isStale(at: now))
        precondition(snapshot.isStale(at: now.addingTimeInterval(901)))
        precondition(snapshot.isStale(at: now.addingTimeInterval(-301)))
        precondition(Snapshot.parseDate("2026-10-28T12:00:00.123456+00:00") != nil)
        let missing = try JSONDecoder().decode(Snapshot.self, from: Data("{\"history\":[],\"trend\":\"NONE\"}".utf8))
        precondition(missing.glucoseText == "—")
        precondition(missing.trendSymbol == "→")
        precondition(missing.isStale(at: now))
        let unknown = try JSONDecoder().decode(Snapshot.self, from: Data("{\"glucose\":123,\"unit\":\"unknown\",\"history\":[]}".utf8))
        precondition(unknown.glucoseText == "—")
        var gate = RefreshGate()
        precondition(gate.begin(at: now))
        precondition(!gate.begin(at: now))
        precondition(!gate.isDue(at: now.addingTimeInterval(601)))
        precondition(gate.hasTimedOut(at: now.addingTimeInterval(121)))
        precondition(!gate.shouldForceKill(at: now.addingTimeInterval(124)))
        precondition(gate.shouldForceKill(at: now.addingTimeInterval(125)))
        gate.finish()
        precondition(!gate.isDue(at: now.addingTimeInterval(599)))
        precondition(gate.isDue(at: now.addingTimeInterval(600)))
        precondition(gate.begin(at: now.addingTimeInterval(5)))
        gate.finish()
        var custom = RefreshGate()
        custom.setInterval(299)
        precondition(custom.interval == 600)
        precondition(custom.begin(at: now))
        custom.finish()
        custom.setInterval(300)
        precondition(custom.isDue(at: now.addingTimeInterval(300)) && !custom.isDue(at: now.addingTimeInterval(299)))
        var retrying = RefreshGate()
        precondition(retrying.begin(at: now))
        retrying.finish()
        retrying.retrySoon(at: now.addingTimeInterval(5))
        precondition(!retrying.isDue(at: now.addingTimeInterval(64)) && retrying.isDue(at: now.addingTimeInterval(65)))
        var early = RefreshGate()
        precondition(!early.staleRetryDue(readingAge: 600, at: now))
        precondition(early.staleRetryDue(readingAge: 1000, at: now))
        precondition(!early.staleRetryDue(readingAge: 1801, at: now))
        precondition(!early.staleRetryDue(readingAge: nil, at: now))
        precondition(early.begin(at: now))
        precondition(!early.staleRetryDue(readingAge: 1000, at: now.addingTimeInterval(130)))
        early.finish()
        precondition(!early.staleRetryDue(readingAge: 1000, at: now.addingTimeInterval(119)))
        precondition(early.staleRetryDue(readingAge: 1000, at: now.addingTimeInterval(120)))
        precondition(GlucoseRange.classify(mgdl: 53, low: 70, high: 180) == .veryLow)
        precondition(GlucoseRange.classify(mgdl: 69, low: 70, high: 180) == .low)
        precondition(GlucoseRange.classify(mgdl: 180, low: 70, high: 180) == .inRange)
        precondition(GlucoseRange.classify(mgdl: 181, low: 70, high: 180) == .high)
        let mmol = try JSONDecoder().decode(Snapshot.self, from: Data("{\"glucose\":3.5,\"unit\":\"mmol/L\",\"history\":[]}".utf8))
        precondition(mmol.range(low: 70, high: 180) == .low)
        precondition(unknown.range(low: 70, high: 180) == nil)
        precondition(Snapshot.ageText(of: now, now: now.addingTimeInterval(59)) == "agora")
        precondition(Snapshot.ageText(of: now, now: now.addingTimeInterval(7 * 60 + 30)) == "há 7min")
        precondition(Snapshot.ageText(of: now, now: now.addingTimeInterval(125 * 60)) == "há 2h 5min")
        precondition(Snapshot.ageText(of: now, now: now.addingTimeInterval(-60)) == "no futuro")
        precondition(!snapshot.hasDeviceStatus)
        precondition(snapshot.averageGlucose == 123 && missing.averageGlucose == nil)
        precondition(TimeInRange(inRange: 65, below: 5, above: 30)?.meetsGoal == false)
        precondition(TimeInRange(inRange: 101, below: 0, above: 0) == nil && TimeInRange(inRange: nil, below: 0, above: 0) == nil)
        var guardState = snapshot
        guardState.smartGuardState = "AUTO_BASAL"
        precondition(guardState.smartGuardText == "Ativo")
        guardState.smartGuardState = "NEW_CODE"
        precondition(guardState.smartGuardText == "NEW_CODE")
        guardState.phoneConnected = false
        precondition(guardState.connectionWarning == "Telemóvel sem ligação ao CareLink")
        guardState.sensorStateCode = "NO_ERROR_MESSAGE"
        precondition(guardState.sensorWarning == nil)
        guardState.sensorStateCode = "SOMETHING_NEW"
        precondition(guardState.sensorWarning == "Sensor: SOMETHING_NEW")
        var alerts = TechnicalAlerts()
        precondition(alerts.evaluate(readingAge: 600, sessionExpired: false, fetchedRecently: true).isEmpty)
        precondition(alerts.evaluate(readingAge: 2000, sessionExpired: false, fetchedRecently: false).isEmpty)
        precondition(alerts.evaluate(readingAge: 2000, sessionExpired: false, fetchedRecently: true) == [.noRecentData(minutes: 33)])
        precondition(alerts.evaluate(readingAge: 2400, sessionExpired: false, fetchedRecently: true).isEmpty)
        precondition(alerts.evaluate(readingAge: 300, sessionExpired: false, fetchedRecently: true).isEmpty)
        precondition(alerts.evaluate(readingAge: 1900, sessionExpired: false, fetchedRecently: true) == [.noRecentData(minutes: 31)])
        precondition(alerts.evaluate(readingAge: 1900, sessionExpired: true, fetchedRecently: true) == [.sessionExpired])
        precondition(alerts.evaluate(readingAge: 1900, sessionExpired: true, fetchedRecently: true).isEmpty)
        guardState.phoneConnected = nil; guardState.pumpCharging = true
        precondition(guardState.connectionWarning == nil && guardState.hasDeviceStatus)
        precondition(snapshot.staleReason(at: now) == nil)
        precondition(snapshot.staleReason(at: now.addingTimeInterval(17 * 60)) == "Última leitura há 17min")
        precondition(snapshot.staleReason(at: now.addingTimeInterval(-301)) == "Hora da leitura à frente do relógio do Mac")
        precondition(missing.staleReason(at: now) == "Hora da leitura indisponível")
        precondition(Snapshot.untilText(of: now, now: now) == "agora")
        precondition(Snapshot.untilText(of: now.addingTimeInterval(200), now: now) == "em 4min")
        precondition(Snapshot.untilText(of: now.addingTimeInterval(3600), now: now) == "em 1h")
        for (raw, symbol) in [("UP_DOUBLE","↑↑"),("DOUBLE_UP","↑↑"),("TRIPLE_DOWN","↓↓↓"),("DOWN_TRIPLE","↓↓↓"),("FLAT","→")] {
            let item = try JSONDecoder().decode(Snapshot.self, from: Data("{\"trend\":\"\(raw)\",\"history\":[]}".utf8))
            precondition(item.trendSymbol == symbol)
        }
        let flat = GlucoseStats(Array(repeating: 100, count: 12), mmol: false)!
        precondition(flat.mean == 100 && flat.standardDeviation == 0 && flat.coefficientOfVariation == 0)
        precondition(abs(flat.gmi - 5.702) < 0.001)
        let spread = GlucoseStats([80, 120] + Array(repeating: 100, count: 10), mmol: false)!
        precondition(abs(spread.standardDeviation - 8.165) < 0.01 && abs(spread.coefficientOfVariation - 8.165) < 0.01)
        precondition(GlucoseStats([100], mmol: false) == nil)
        let mmolStats = GlucoseStats(Array(repeating: 100 / GlucoseRange.mmolFactor, count: 12), mmol: true)!
        precondition(abs(mmolStats.gmi - 5.702) < 0.001)
        precondition(GlucoseRange.effective(manualLow: 70, manualHigh: 180, pump: 70...200, usePump: true) == (70, 200))
        precondition(GlucoseRange.effective(manualLow: 70, manualHigh: 180, pump: 70...200, usePump: false) == (70, 180))
        precondition(GlucoseRange.effective(manualLow: 70, manualHigh: 180, pump: nil, usePump: true) == (70, 180))
        let line = (0..<48).map { ChartPoint(date: now.addingTimeInterval(Double($0) * 300), glucose: 100 + Double($0)) }
        let path = Sparkline.path(line, width: 30, height: 14, mmol: false)
        precondition(path.count == 37 && abs(path.last!.x - 30) < 0.001 && path.first!.x >= 0)
        precondition(path.allSatisfy { $0.y >= 0 && $0.y <= 14 } && path.last!.y > path.first!.y)
        let steady = Sparkline.path(Array(line.prefix(10)).map { ChartPoint(date: $0.date, glucose: 100) }, width: 30, height: 14, mmol: false)
        precondition(steady.allSatisfy { abs($0.y - 7) < 0.001 })
        precondition(Sparkline.path([], width: 30, height: 14, mmol: false).isEmpty)
        precondition(Snapshot.compactDuration(hours: 71.9) == "2d 23h" && Snapshot.compactDuration(hours: 5.5) == "5h")
        precondition(Snapshot.compactDuration(hours: 0.4) == "<1h")
        precondition(LifeRule.sensor.level(hoursLeft: 30) == .normal && LifeRule.sensor.level(hoursLeft: 23.9) == .warning)
        precondition(LifeRule.sensor.level(hoursLeft: 5) == .critical && LifeRule.sensor.level(hoursLeft: nil) == .normal)
        precondition(LifeRule.infusion.level(hoursLeft: 11) == .warning && LifeRule.infusion.level(hoursLeft: 1) == .critical)
        var life = TechnicalAlerts()
        precondition(life.evaluateLife(sensor: .normal, sensorHours: 40, infusion: .normal, infusionHours: 50).isEmpty)
        precondition(life.evaluateLife(sensor: .warning, sensorHours: 20, infusion: .normal, infusionHours: 50)
                     == [.consumableEnding(.sensor, .warning, hoursLeft: 20)])
        precondition(life.evaluateLife(sensor: .warning, sensorHours: 19, infusion: .normal, infusionHours: 49).isEmpty)
        precondition(life.evaluateLife(sensor: .normal, sensorHours: nil, infusion: .normal, infusionHours: nil).isEmpty)
        precondition(life.evaluateLife(sensor: .critical, sensorHours: 5, infusion: .critical, infusionHours: nil)
                     == [.consumableEnding(.sensor, .critical, hoursLeft: 5), .consumableEnding(.infusion, .critical, hoursLeft: nil)])
        precondition(life.evaluateLife(sensor: .normal, sensorHours: 160, infusion: .normal, infusionHours: 72).isEmpty)
        precondition(life.evaluateLife(sensor: .warning, sensorHours: 23, infusion: .normal, infusionHours: 70).count == 1)
        var restored = TechnicalAlerts(sensorLevel: .critical, infusionLevel: .warning)
        precondition(restored.evaluateLife(sensor: .critical, sensorHours: 4, infusion: .warning, infusionHours: 9).isEmpty)
        precondition(restored.evaluateLife(sensor: .critical, sensorHours: 3, infusion: .critical, infusionHours: 1).count == 1)
        precondition(restored.sensorLevel == .critical && restored.infusionLevel == .critical)
        var ending = snapshot
        ending.sensorHoursLeft = 5; ending.infusionMinutesLeft = 600; ending.infusionStatusCode = "NORMAL"
        precondition(ending.sensorLife == .critical && ending.infusionLife == .warning)
        ending.infusionStatusCode = "END_OF_LIFE"
        precondition(ending.infusionLife == .critical)
        L10n.choice = .english
        precondition(Snapshot.ageText(of: now, now: now.addingTimeInterval(7 * 60 + 30)) == "7min ago")
        precondition(Snapshot.untilText(of: now.addingTimeInterval(200), now: now) == "in 4min")
        precondition(missing.staleReason(at: now) == "Reading time unavailable")
        precondition(guardState.sensorWarning == "Sensor: SOMETHING_NEW")
        precondition(tr("info.tir").hasPrefix("Share of the last 24h"))
        L10n.choice = .portuguese
        precondition(tr("info.tir").hasPrefix("Percentagem das últimas 24h"))
        precondition(tr("há %@h %@min", "2", "5") == "há 2h 5min")
        // Sparkle's windows follow the app's language choice (AppleLanguages), or macOS when automatic.
        precondition(AppLanguage.portuguese.bundleLanguages == ["pt-PT"] && AppLanguage.english.bundleLanguages == ["en"])
        precondition(AppLanguage.system.bundleLanguages == nil)
        let suite = "carelink.checks.\(UUID().uuidString)"
        let scratch = UserDefaults(suiteName: suite)!
        scratch.set("en", forKey: "language")
        AppLanguage.applyToBundles(defaults: scratch)
        precondition(scratch.stringArray(forKey: "AppleLanguages") == ["en"])
        scratch.set("system", forKey: "language")
        AppLanguage.applyToBundles(defaults: scratch)
        precondition(scratch.persistentDomain(forName: suite)?["AppleLanguages"] == nil)
        scratch.removePersistentDomain(forName: suite)
        print("PASS: snapshot values, timezone parsing, stale/future data, missing fields, unknown units, trend, refresh interval, configurable interval, glucose range, reading age, time until refresh, stale reasons, early stale refresh, retry after failure, time in range, SmartGuard, connection, sensor status, technical alerts, consumable life, trend aliases, glucose stats, effective target, sparkline, Portuguese/English text, bundle language, overlap and timeout")
    }
}
